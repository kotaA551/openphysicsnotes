import fs from 'node:fs';
import path from 'node:path';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
import { JSDOM } from 'jsdom';
const [dir, label] = process.argv.slice(2);
const chapter = '10-Condensed-matter-physics';
const htmlPath = path.join(dir, 'server/app/chapters', chapter + '.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const doc = new JSDOM(html).window.document;
const bytes = x => Buffer.byteLength(x);
const size = x => ({raw:bytes(x), gzip:gzipSync(x,{level:9}).length, br:brotliCompressSync(x,{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).length});
const scripts = [...doc.querySelectorAll('script')];
const flight = scripts.filter(s=>s.textContent.includes('self.__next_f.push')).map(s=>s.outerHTML).join('');
const route = fs.readFileSync(path.join(dir,'server/app/chapters',chapter+'.rsc'));
const assetUrls = [...new Set([...doc.querySelectorAll('script[src],link[rel="stylesheet"]')].map(n=>n.getAttribute('src')||n.getAttribute('href')))].filter(x=>x.startsWith('/_next/'));
const assets = assetUrls.map(url=>({url,...size(fs.readFileSync(path.join(dir,url.replace('/_next/',''))))}));
const result={label,chapter,html:size(html),embeddedFlight:size(flight),routePayload:size(route),assets,mathCount:doc.querySelectorAll('.katex').length,mathML:doc.querySelectorAll('math').length,headings:[...doc.querySelectorAll('article h2,article h3,article h4')].map(x=>({id:x.id,text:x.textContent})),canonical:doc.querySelector('link[rel="canonical"]')?.href,alternates:[...doc.querySelectorAll('link[hreflang]')].map(x=>({lang:x.hreflang,href:x.href})),mathVisuals:[...doc.querySelectorAll('.katex-html')].map(x=>x.outerHTML),articleText:doc.querySelector('article')?.textContent};
fs.mkdirSync('../results',{recursive:true});
fs.writeFileSync(`../results/${label}.json`,JSON.stringify(result,null,2));
fs.copyFileSync(htmlPath,`../results/${label}.html`);
console.log(JSON.stringify({label,html:result.html,embeddedFlight:result.embeddedFlight,routePayload:result.routePayload,mathCount:result.mathCount,mathML:result.mathML,assets},null,2));
